// Compiles the native engine's GLSL (native/shaders) to SPIR-V and writes native/src/shaders.inc, which the engine
// embeds, so building the engine needs no shader compiler. Run it after changing a shader; tests/native-plan.test.ts
// checks the header matches the sources.
//
//   node scripts/native-shaders.ts [--glslc path]
//
// glslc comes with the Vulkan SDK and with the Android NDK (shader-tools/<host>/glslc).
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { shaderHash, SHADER_DIR, SHADER_HEADER, shaderSymbol } from "./lib/native.ts";

function findGlslc(): string {
  const args = process.argv.slice(2);
  const given = args.indexOf("--glslc");
  if (given >= 0) return args[given + 1];
  if (process.env.GLSLC) return process.env.GLSLC;
  const exe = process.platform === "win32" ? "glslc.exe" : "glslc";
  const candidates: string[] = [];
  if (process.env.VULKAN_SDK) candidates.push(join(process.env.VULKAN_SDK, "bin", exe), join(process.env.VULKAN_SDK, "Bin", exe));
  for (const sdk of [process.env.ANDROID_NDK_HOME, process.env.ANDROID_NDK_ROOT, process.env.ANDROID_NDK_LATEST_HOME]) {
    if (!sdk) continue;
    const tools = join(sdk, "shader-tools");
    if (existsSync(tools)) for (const host of readdirSync(tools)) candidates.push(join(tools, host, exe));
  }
  for (const home of [process.env.ANDROID_HOME, process.env.ANDROID_SDK_ROOT]) {
    const ndks = home && join(home, "ndk");
    if (!ndks || !existsSync(ndks)) continue;
    for (const version of readdirSync(ndks).sort().reverse()) {
      const tools = join(ndks, version, "shader-tools");
      if (existsSync(tools)) for (const host of readdirSync(tools)) candidates.push(join(tools, host, exe));
    }
  }
  return candidates.find((c) => existsSync(c)) ?? exe;
}

const glslc = findGlslc();
const sources = readdirSync(SHADER_DIR)
  .filter((f) => /\.(vert|frag|comp)$/.test(f))
  .sort();
const work = mkdtempSync(join(tmpdir(), "aevk-shaders-"));
const lines = [
  "// Generated by scripts/native-shaders.ts from native/shaders; do not edit.",
  "#pragma once",
  "#include <cstddef>",
  "#include <cstdint>",
  "",
];
try {
  for (const file of sources) {
    const out = join(work, `${file}.spv`);
    execFileSync(glslc, ["-O", "--target-env=vulkan1.0", "-o", out, join(SHADER_DIR, file)], { stdio: "inherit" });
    const spirv = readFileSync(out);
    const words = new Uint32Array(spirv.buffer, spirv.byteOffset, spirv.byteLength / 4);
    const rows: string[] = [];
    for (let i = 0; i < words.length; i += 8) rows.push("  " + Array.from(words.subarray(i, i + 8), (w) => `0x${w.toString(16).padStart(8, "0")}u`).join(", ") + ",");
    lines.push(`// ${file} sha256 ${shaderHash(file)}`);
    lines.push(`static const uint32_t ${shaderSymbol(file)}[] = {`, ...rows, "};", "");
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
writeFileSync(SHADER_HEADER, lines.join("\n"));
console.log(`wrote ${SHADER_HEADER} (${sources.length} shaders, ${glslc})`);
