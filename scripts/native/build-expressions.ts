// Bundles src/native/qjs/entry.ts, with the app's parser, evaluator and expression engine, into the script the
// native core runs in QuickJS: native/core/expressions/bundle.js. Run it after changing any of them; the native
// parity check (scripts/reports/native-parity.ts --expressions) fails when the bundle is out of date.
//
//   node scripts/native/build-expressions.ts [--check]
//
// --check only reports whether the committed bundle matches the sources.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const OUT = resolve("native/core/expressions/bundle.js");

/**
 * QuickJS has no TextDecoder. The native core provides aep_native.decodeText; the fallback lets the bundle also run
 * in the plain qjs shell for debugging.
 */
const PRELUDE = `
if (typeof globalThis.TextDecoder === "undefined") {
  globalThis.TextDecoder = class TextDecoder {
    constructor(label = "utf-8") { this.latin1 = /latin1|ascii|iso-8859-1/i.test(label); }
    decode(bytes) {
      if (!bytes) return "";
      const view = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes.buffer ?? bytes, bytes.byteOffset ?? 0, bytes.byteLength);
      if (globalThis.aep_native) return globalThis.aep_native.decodeText(view, this.latin1);
      let out = "";
      if (this.latin1) {
        for (let i = 0; i < view.length; i++) out += String.fromCharCode(view[i]);
        return out;
      }
      for (let i = 0; i < view.length; ) {
        const b = view[i];
        const n = b < 0x80 ? 0 : b >= 0xf0 && b < 0xf5 ? 3 : b >= 0xe0 ? 2 : b >= 0xc2 && b < 0xe0 ? 1 : -1;
        let code = n === 0 ? b : n === 1 ? b & 0x1f : n === 2 ? b & 0x0f : b & 0x07;
        let ok = n >= 0 && i + n < view.length;
        for (let k = 1; ok && k <= n; k++) {
          const c = view[i + k];
          if ((c & 0xc0) !== 0x80) ok = false;
          else code = (code << 6) | (c & 0x3f);
        }
        if (ok && n > 0 && (code < [0, 0x80, 0x800, 0x10000][n] || code > 0x10ffff || (code >= 0xd800 && code < 0xe000))) ok = false;
        out += ok ? String.fromCodePoint(code) : "\ufffd";
        i += ok ? n + 1 : 1;
      }
      return out;
    }
  };
}
`;

const result = await build({
  entryPoints: [resolve("src/native/qjs/entry.ts")],
  bundle: true,
  format: "iife",
  target: "es2022",
  platform: "neutral",
  minifySyntax: true,
  minifyWhitespace: true,
  legalComments: "eof",
  banner: { js: `// Generated by scripts/native/build-expressions.ts from src/; do not edit.\n${PRELUDE}` },
  write: false,
});
const text = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== text) {
    console.error(`${OUT} is out of date: run node scripts/native/build-expressions.ts`);
    process.exit(1);
  }
  console.log("expression bundle is up to date");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${(text.length / 1024).toFixed(0)} KiB)`);
}
