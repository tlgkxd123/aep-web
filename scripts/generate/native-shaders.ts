// Compiles the native engine's GLSL to SPIR-V and writes the headers the engine embeds, so building the engine needs
// no shader compiler. Run it after changing a shader; tests/native-plan.test.ts checks the headers match the sources.
//
// - native/shaders/*.{vert,frag} -> native/src/shaders.inc (kShader_<file>).
// - The effect shaders scripts/lib/native-fx.ts lists, taken from the TypeScript effects and converted to Vulkan GLSL
//   (scripts/lib/fx-convert.ts) -> native/src/fx_shaders.inc (fx::<name>, with their uniforms' offsets).
//
// Shaders whose source has not changed keep the SPIR-V already in the headers.
//
//   node scripts/generate/native-shaders.ts [--glslc path] [--glslang path]
//
// glslc comes with the Vulkan SDK and with the Android NDK (shader-tools/<host>/glslc); without it, glslangValidator
// and spirv-opt (Khronos' packages, also in the Vulkan SDK) do the same.
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { convertFx } from "../lib/fx-convert.ts";
import { FX_HEADER, shaderHash, SHADER_DIR, SHADER_HEADER, shaderSymbol } from "../lib/native.ts";
import { describeFx, FX_SHADERS, fxHash, fxSource } from "../lib/native-fx.ts";

const args = process.argv.slice(2);
const option = (name: string) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

function onPath(exe: string): boolean {
  try {
    execFileSync(process.platform === "win32" ? "where" : "which", [exe], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

function findGlslc(): string | undefined {
  const given = option("--glslc") ?? process.env.GLSLC;
  if (given) return given;
  const exe = process.platform === "win32" ? "glslc.exe" : "glslc";
  const candidates: string[] = [];
  if (process.env.VULKAN_SDK) candidates.push(join(process.env.VULKAN_SDK, "bin", exe), join(process.env.VULKAN_SDK, "Bin", exe));
  for (const sdk of [process.env.ANDROID_NDK_HOME, process.env.ANDROID_NDK_ROOT, process.env.ANDROID_NDK_LATEST_HOME]) {
    if (!sdk) continue;
    const tools = join(sdk, "shader-tools");
    if (existsSync(tools)) for (const host of readdirSync(tools)) candidates.push(join(tools, host, exe));
  }
  for (const home of [process.env.ANDROID_HOME, process.env.ANDROID_SDK_ROOT]) {
    const ndks = home && join(home, "ndk");
    if (!ndks || !existsSync(ndks)) continue;
    for (const version of readdirSync(ndks).sort().reverse()) {
      const tools = join(ndks, version, "shader-tools");
      if (existsSync(tools)) for (const host of readdirSync(tools)) candidates.push(join(tools, host, exe));
    }
  }
  return candidates.find((c) => existsSync(c)) ?? (onPath(exe) ? exe : undefined);
}

const work = mkdtempSync(join(tmpdir(), "aevk-shaders-"));
let compiler = "";

/** SPIR-V words of a GLSL file (its stage from the extension), optimized for performance. */
function compile(file: string): Uint32Array {
  const out = `${file}.spv`;
  const glslc = findGlslc();
  if (glslc) {
    compiler = glslc;
    execFileSync(glslc, ["-O", "--target-env=vulkan1.0", "-o", out, file], { stdio: "inherit" });
  } else {
    const glslang = option("--glslang") ?? "glslangValidator";
    compiler = `${glslang} + spirv-opt`;
    const raw = `${file}.raw.spv`;
    execFileSync(glslang, ["-V", "--target-env", "vulkan1.0", "-o", raw, file], { stdio: ["ignore", "ignore", "inherit"] });
    execFileSync("spirv-opt", ["-O", "--target-env=vulkan1.0", "-o", out, raw], { stdio: "inherit" });
  }
  const spirv = readFileSync(out);
  return new Uint32Array(spirv.buffer.slice(spirv.byteOffset, spirv.byteOffset + spirv.byteLength));
}

function words(symbol: string, code: Uint32Array): string[] {
  const rows: string[] = [];
  for (let i = 0; i < code.length; i += 8) rows.push("  " + Array.from(code.subarray(i, i + 8), (w) => `0x${w.toString(16).padStart(8, "0")}u`).join(", ") + ",");
  return [`static const uint32_t ${symbol}[] = {`, ...rows, "};"];
}

/** The SPIR-V arrays a header already holds, by the hash comment above each. */
function existing(header: string): Map<string, string[]> {
  const blocks = new Map<string, string[]>();
  if (!existsSync(header)) return blocks;
  const lines = readFileSync(header, "utf8").split("\n");
  for (let i = 0; i < lines.length; i++) {
    const m = /^\/\/ (\S+) sha256 ([0-9a-f]{64})$/.exec(lines[i]);
    if (!m || !lines[i + 1]?.startsWith("static const uint32_t ")) continue;
    const end = lines.indexOf("};", i + 1);
    blocks.set(`${m[1]} ${m[2]}`, lines.slice(i + 1, end + 1));
  }
  return blocks;
}

try {
  // Engine shaders.
  const reuse = existing(SHADER_HEADER);
  const sources = readdirSync(SHADER_DIR)
    .filter((f) => /\.(vert|frag|comp)$/.test(f))
    .sort();
  const lines = ["// Generated by scripts/generate/native-shaders.ts from native/shaders; do not edit.", "#pragma once", "#include <cstddef>", "#include <cstdint>", ""];
  for (const file of sources) {
    const hash = shaderHash(file);
    lines.push(`// ${file} sha256 ${hash}`, ...(reuse.get(`${file} ${hash}`) ?? words(shaderSymbol(file), compile(join(SHADER_DIR, file)))), "");
  }
  writeFileSync(SHADER_HEADER, lines.join("\n"));

  // Effect shaders.
  const reuseFx = existing(FX_HEADER);
  const fx = [
    "// Generated by scripts/generate/native-shaders.ts from the effect shaders scripts/lib/native-fx.ts lists; do not edit.",
    "// Included by fx.h.",
    "#pragma once",
    "",
    "namespace aevk {",
    "",
  ];
  const types: Record<string, string> = {
    float: "Float", vec2: "Vec2", vec3: "Vec3", vec4: "Vec4", int: "Int", ivec2: "IVec2", ivec3: "IVec3", ivec4: "IVec4",
    uint: "UInt", uvec2: "UVec2", uvec3: "UVec3", uvec4: "UVec4", bool: "Bool", mat2: "Mat2", mat3: "Mat3", mat4: "Mat4",
  };
  const names = new Set<string>();
  for (const entry of FX_SHADERS) {
    if (!/^[a-z][a-z0-9_]*$/.test(entry.name) || names.has(entry.name)) throw new Error(`effect shader name "${entry.name}" is not a new C++ identifier`);
    names.add(entry.name);
    const source = await fxSource(entry);
    const hash = fxHash(source);
    const label = describeFx(entry.source);
    const converted = convertFx(source, label);
    let block = reuseFx.get(`${entry.name} ${hash}`);
    if (!block) {
      const file = join(work, `${entry.name}.frag`);
      writeFileSync(file, converted.source);
      block = words(`kFx_${entry.name}`, compile(file));
    }
    fx.push(`// ${entry.name} sha256 ${hash}`, `// ${label}`, ...block);
    if (converted.uniforms.length) {
      fx.push(`static const FxUniform kFxUniforms_${entry.name}[] = {`);
      for (const u of converted.uniforms) fx.push(`  {"${u.name}", FxType::${types[u.type]}, ${u.count}, ${u.offset}, ${u.stride}},`);
      fx.push("};");
    }
    if (converted.samplers.length) fx.push(`static const char* const kFxSamplers_${entry.name}[] = {${converted.samplers.map((s) => `"${s}"`).join(", ")}};`);
    fx.push("");
  }
  fx.push("namespace fx {", "enum Id : uint32_t {", ...FX_SHADERS.map((e) => `  ${e.name},`), "  kCount", "};", "}  // namespace fx", "");
  fx.push("static const FxShader kFxShaders[fx::kCount] = {");
  for (const { name } of FX_SHADERS) {
    const block = fx.join("\n");
    const uniforms = block.includes(`kFxUniforms_${name}[]`) ? [`kFxUniforms_${name}`, `uint32_t(sizeof kFxUniforms_${name} / sizeof(FxUniform))`] : ["nullptr", "0"];
    const samplers = block.includes(`kFxSamplers_${name}[]`) ? [`kFxSamplers_${name}`, `uint32_t(sizeof kFxSamplers_${name} / sizeof(const char*))`] : ["nullptr", "0"];
    const source = await fxSource(FX_SHADERS.find((e) => e.name === name)!);
    fx.push(`  {"${name}", kFx_${name}, sizeof kFx_${name}, ${uniforms.join(", ")}, ${samplers.join(", ")}, ${convertFx(source, name).paramBytes}},`);
  }
  fx.push("};", "", "}  // namespace aevk", "");
  writeFileSync(FX_HEADER, fx.join("\n"));
  console.log(`wrote ${SHADER_HEADER} (${sources.length} shaders) and ${FX_HEADER} (${FX_SHADERS.length} effect shaders)${compiler ? `, compiled with ${compiler}` : ", nothing to compile"}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
